package com.rentals.service;

import com.rentals.ui.LoginView;
import com.rentals.ui.dashboard.DashboardView;
import com.rentals.ui.expenses.ExpensesView;
import com.rentals.ui.payments.PaymentsView;
import com.rentals.ui.properties.PropertiesView;
import com.rentals.ui.reminders.RemindersView;
import com.rentals.ui.reports.ReportsView;
import com.rentals.ui.rooms.RoomsView;
import com.rentals.ui.settings.SettingsView;
import com.rentals.ui.tenancies.TenanciesView;
import com.rentals.ui.tenants.TenantsView;
import javafx.geometry.Insets;
import javafx.geometry.Pos;
import javafx.scene.Scene;
import javafx.scene.control.Button;
import javafx.scene.control.Label;
import javafx.scene.input.KeyEvent;
import javafx.scene.layout.*;
import javafx.stage.Stage;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Main application shell with hamburger menu sidebar.
 * After login, this is the first screen shown.
 * Menu items swap the center content area (single window navigation).
 */
public class MainLayout {

    private final Stage stage;
    private final BorderPane root = new BorderPane();
    private final StackPane contentArea = new StackPane();
    private final HBox mainContainer = new HBox(0);
    private final Map<String, Button> navButtons = new LinkedHashMap<>();

    private VBox sidebar;
    private boolean sidebarCollapsed = false;

    public MainLayout(Stage stage) {
        this.stage = stage;
        root.getStyleClass().add("root");

        // Make sure every active tenancy has a rent charge for the current month
        // BEFORE the dashboard reads its totals. Idempotent, so repeated logins
        // do not create duplicate charges.
        int autoGenerated = new com.rentals.dao.RentChargeDAO().generateForCurrentMonth();
        if (autoGenerated > 0) {
            AuditService.log("RENT_CHARGE_AUTO",
                "Auto-generated " + autoGenerated + " rent charge(s) for the current month");
        }

        buildUI();
        installKeyboardShortcuts();

        // Opt-in background scanning while the admin is logged in. The actual
        // sends only happen when reminder_auto_send_enabled is true.
        ReminderScheduler.start();
    }

    private void buildUI() {
        // ---------- Top Bar ----------
        HBox topBar = new HBox(15);
        topBar.getStyleClass().add("top-bar");
        topBar.setPadding(new Insets(12, 25, 12, 25));
        topBar.setAlignment(Pos.CENTER_LEFT);

        Button hamburgerBtn = new Button("☰");
        hamburgerBtn.setPrefWidth(45);
        hamburgerBtn.setPrefHeight(40);
        hamburgerBtn.setStyle("-fx-font-size: 18px; -fx-background-color: transparent; -fx-text-fill: #1976D2; -fx-font-weight: bold; -fx-cursor: hand;");
        hamburgerBtn.setOnAction(e -> toggleSidebar());

        Label appTitle = new Label("🏠 RentalSys");
        appTitle.getStyleClass().add("top-bar-title");

        Region spacer = new Region();
        HBox.setHgrow(spacer, Priority.ALWAYS);

        Label userLabel = new Label("Admin");
        userLabel.getStyleClass().add("top-bar-user");

        Button logoutBtn = new Button("Logout");
        logoutBtn.getStyleClass().add("btn-danger");
        logoutBtn.setPrefHeight(40);
        logoutBtn.setOnAction(e -> handleLogout());

        // Theme toggle (🌙 dark / ☀️ light)
        Button themeBtn = new Button(ThemeManager.isDark() ? "☀️ Light" : "🌙 Dark");
        themeBtn.getStyleClass().add("btn-secondary");
        themeBtn.setPrefHeight(40);
        themeBtn.setOnAction(e -> {
            ThemeManager.toggle(topBar.getScene());
            themeBtn.setText(ThemeManager.isDark() ? "☀️ Light" : "🌙 Dark");
        });

        topBar.getChildren().addAll(hamburgerBtn, appTitle, spacer, themeBtn, userLabel, logoutBtn);
        root.setTop(topBar);

        // ---------- Content Area ----------
        contentArea.getStyleClass().add("card");

        // ---------- Sidebar + Content ----------
        sidebar = buildSidebar();
        mainContainer.getChildren().addAll(sidebar, contentArea);
        HBox.setHgrow(contentArea, Priority.ALWAYS);
        root.setCenter(mainContainer);

        // First screen after login: dashboard
        showDashboard();
    }

    private VBox buildSidebar() {
        VBox box = new VBox(6);
        box.getStyleClass().add("sidebar");
        box.setPadding(new Insets(20, 10, 20, 10));
        box.setPrefWidth(220);
        box.setMinWidth(220);
        box.setMaxWidth(220);

        Label appTitle = new Label("🏠 RentalSys");
        appTitle.getStyleClass().add("sidebar-title");

        box.getChildren().add(appTitle);
        navButtons.clear();

        addNavButton(box, "Dashboard", "📊  Dashboard", this::showDashboard);
        addNavButton(box, "Properties", "🏢  Properties", () -> navigateTo("Properties"));
        addNavButton(box, "Rooms", "🛏️  Rooms", () -> navigateTo("Rooms"));
        addNavButton(box, "Tenants", "👥  Tenants", () -> navigateTo("Tenants"));
        addNavButton(box, "Tenancies", "📄  Tenancies", () -> navigateTo("Tenancies"));
        addNavButton(box, "Payments", "💰  Payments", () -> navigateTo("Payments"));
        addNavButton(box, "Expenses", "💸  Expenses", () -> navigateTo("Expenses"));
        addNavButton(box, "Reports", "📊  Reports", () -> navigateTo("Reports"));
        addNavButton(box, "Reminders", "🔔  Reminders", () -> navigateTo("Reminders"));
        addNavButton(box, "Settings", "⚙️  Settings", () -> navigateTo("Settings"));

        return box;
    }

    private void addNavButton(VBox box, String key, String text, Runnable action) {
        Button btn = new Button(text);
        btn.getStyleClass().add("sidebar-button");
        btn.setPrefWidth(180);
        btn.setPrefHeight(44);
        btn.setMaxWidth(180);
        btn.setAlignment(Pos.CENTER_LEFT);
        btn.setOnAction(e -> action.run());
        navButtons.put(key, btn);
        box.getChildren().add(btn);
    }

    /** Highlights the button for the active module. */
    private void markActive(String module) {
        navButtons.forEach((key, btn) -> {
            btn.getStyleClass().remove("sidebar-button-active");
            if (key.equals(module)) btn.getStyleClass().add("sidebar-button-active");
        });
    }

    /** Toggle sidebar collapsed/expanded state. */
    private void toggleSidebar() {
        sidebarCollapsed = !sidebarCollapsed;

        if (sidebarCollapsed) {
            sidebar.setPrefWidth(60);
            sidebar.setMinWidth(60);
            sidebar.setMaxWidth(60);
            // Keep only the icon (first token) when collapsed
            for (var child : sidebar.getChildren()) {
                if (child instanceof Button btn && btn.getText() != null && btn.getText().contains(" ")) {
                    btn.setText(btn.getText().substring(0, btn.getText().indexOf(" ")));
                }
            }
        } else {
            // Rebuild to restore the full labels
            int index = mainContainer.getChildren().indexOf(sidebar);
            VBox expanded = buildSidebar();
            mainContainer.getChildren().set(index, expanded);
            sidebar = expanded;
            markActive(currentModule);
        }
    }

    private String currentModule = "Dashboard";

    /** Shows a module by name in the center content area. */
    public void navigateTo(String module) {
        currentModule = module;
        Pane content = switch (module) {
            case "Properties" -> PropertiesView.create(stage, this::showDashboard);
            case "Rooms" -> RoomsView.create(stage, this::showDashboard);
            case "Tenants" -> TenantsView.create(stage, this::showDashboard);
            case "Tenancies" -> TenanciesView.create(stage, this::showDashboard);
            case "Payments" -> PaymentsView.create(stage, this::showDashboard);
            case "Expenses" -> ExpensesView.create(stage, this::showDashboard);
            case "Reports" -> ReportsView.create(stage, this::showDashboard);
            case "Reminders" -> RemindersView.create(stage, this::showDashboard);
            case "Settings" -> SettingsView.create(stage, this::showDashboard,
                () -> navigateTo("Reminders"));
            default -> null;
        };
        if (content != null) {
            showContent(content, module);
            markActive(module);
        }
    }

    /** Show the dashboard view in the content area. */
    public void showDashboard() {
        currentModule = "Dashboard";
        contentArea.getChildren().setAll(DashboardView.create(this::navigateTo));
        stage.setTitle("Rental Management System - Dashboard");
        markActive("Dashboard");
    }

    /** Show any content pane in the center area. */
    public void showContent(Pane content, String title) {
        contentArea.getChildren().setAll(content);
        stage.setTitle("Rental Management System - " + title);
    }

    /** Global keyboard shortcuts (P, R, T, A, M, B, E, S, Esc = dashboard). */
    private void installKeyboardShortcuts() {
        root.addEventFilter(KeyEvent.KEY_PRESSED, e -> {
            // Ignore shortcuts while typing in a text field
            if (e.getTarget() instanceof javafx.scene.control.TextInputControl) return;

            switch (e.getCode()) {
                case P -> navigateTo("Properties");
                case R -> navigateTo("Rooms");
                case T -> navigateTo("Tenants");
                case A -> navigateTo("Tenancies");
                case M -> navigateTo("Payments");
                case X -> navigateTo("Expenses");
                case B -> navigateTo("Reports");
                case E -> navigateTo("Reminders");
                case S -> navigateTo("Settings");
                case ESCAPE -> showDashboard();
                default -> { }
            }
        });
    }

    private void handleLogout() {
        ReminderScheduler.stop();
        AuditService.log("LOGOUT", "Admin logged out");
        new SessionService().destroySession();
        stage.close();
        Stage loginStage = new Stage();
        loginStage.setMaximized(true);
        Scene loginScene = new Scene(new LoginView(), 500, 550);
        ThemeManager.applyTo(loginScene);
        loginStage.setScene(loginScene);
        loginStage.setTitle("Rental Management System - Login");
        loginStage.show();
    }

    public BorderPane getRoot() {
        return root;
    }
}
